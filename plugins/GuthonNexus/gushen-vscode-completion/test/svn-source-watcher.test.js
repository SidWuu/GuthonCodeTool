test('flushes one batch per workspace and reports a single cascade refresh', async () => {
  const reindexed = [];
  const changes = [];
  const watcher = new SvnSourceWatcher({
    vscode: {},
    backend: {
      reindexFiles: async (workspaceKey, paths) => {
        reindexed.push(paths);
        return { ok: true, paths, reindex: { changed: paths.length }, indexGeneration: 'g1' };
      },
    },
    onChanged: async (workspaceKey, result) => { changes.push({ workspaceKey, result }); },
    debounceMs: 5,
  });
  const root = path.resolve('/checkout/pages/SYS-1');
  const workspace = { workspaceKey: 'products.demo' };
  const workingCopy = { root, localSubdir: 'pages/SYS-1' };
  watcher._schedule(workspace, workingCopy, { fsPath: path.join(root, '0', 'PG-1.json') });
  watcher._schedule(workspace, workingCopy, { fsPath: path.join(root, '0', 'PG-2.json') });

  // 同一工作区只保留一个待处理批次。
  assert.equal(watcher.timers.size, 1);
  await new Promise((resolve) => setTimeout(resolve, 40));

  assert.deepEqual(reindexed, [['pages/SYS-1/0/PG-1.json', 'pages/SYS-1/0/PG-2.json']]);
  assert.equal(changes.length, 1);
  assert.equal(changes[0].workspaceKey, 'products.demo');
  assert.deepEqual(changes[0].result.paths.sort(), ['pages/SYS-1/0/PG-1.json', 'pages/SYS-1/0/PG-2.json']);
  assert.equal(changes[0].result.ok, true);
  watcher.dispose();
});

function queuedWatcher(backend, extra = {}) {
  const outputs = [], changes = [];
  const watcher = new SvnSourceWatcher({ vscode: {}, backend, debounceMs: 10000,
    onOutput: text => outputs.push(text), onChanged: async (_key, result) => changes.push(result), ...extra });
  const enqueue = (name) => watcher._schedule({ workspaceKey: 'projects.demo' },
    { root: path.resolve('/checkout/demo'), localSubdir: '.' },
    { fsPath: path.resolve('/checkout/demo/systems/SYS/pages', name) });
  return { watcher, outputs, changes, enqueue };
}

test('already indexed update events stay quiet and refresh an external generation only once', async () => {
  let calls = 0;
  const { watcher, outputs, changes, enqueue } = queuedWatcher({ reindexFiles: async (_key, paths) => {
    calls++;
    return { ok: true, paths: [], reindex: { changed: 0, skippedFiles: paths.length }, indexGeneration: 'external-update' };
  } });
  try {
    for (let i = 0; i < 42; i++) { enqueue(`${i}.json`); enqueue(`${i}.json`); }
    await watcher._flush('projects.demo');
    enqueue('0.json');
    await watcher._flush('projects.demo');
    assert.equal(calls, 2);
    assert.equal(changes.length, 1);
    assert.equal(changes[0].paths.length, 42);
    assert.deepEqual(outputs, []);
  } finally { watcher.dispose(); }
});

test('events arriving during a batch remain queued without concurrent backend requests', async () => {
  let complete, began;
  const started = new Promise(resolve => { began = resolve; });
  const calls = [];
  const { watcher, enqueue, changes } = queuedWatcher({ reindexFiles: async (_key, paths) => {
    calls.push(paths);
    if (calls.length === 1) { began(); await new Promise(resolve => { complete = resolve; }); }
    return { ok: true, paths, reindex: { changed: paths.length }, indexGeneration: String(calls.length) };
  } });
  try {
    enqueue('first.json');
    const first = watcher._flush('projects.demo');
    await started;
    enqueue('second.json');
    const overlapping = watcher._flush('projects.demo');
    assert.equal(calls.length, 1);
    complete();
    await Promise.all([first, overlapping]);
    await watcher._flush('projects.demo');
    assert.equal(calls.length, 2);
    assert.equal(calls[1][0], 'systems/SYS/pages/second.json');
    assert.equal(changes.length, 2);
  } finally { watcher.dispose(); }
});

